import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = [
  'color-kumo-canvas', 'color-kumo-elevated', 'color-kumo-recessed',
  'color-kumo-base', 'color-kumo-control', 'color-kumo-tint',
  'color-kumo-line', 'color-kumo-hairline', 'color-kumo-shadow-drop',
  'color-kumo-brand', 'color-kumo-brand-hover', 'color-kumo-focus',
  'color-kumo-info', 'color-kumo-info-tint',
  'color-kumo-warning', 'color-kumo-warning-tint',
  'color-kumo-danger', 'color-kumo-danger-tint',
  'color-kumo-success', 'color-kumo-success-tint',
  'text-color-kumo-default', 'text-color-kumo-strong',
  'text-color-kumo-inverse', 'text-color-kumo-subtle',
  'text-color-kumo-inactive', 'text-color-kumo-link',
  'text-color-kumo-info', 'text-color-kumo-success',
  'text-color-kumo-danger', 'text-color-kumo-warning',
];

function declarations(css) {
  return Object.fromEntries([...css.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)]
    .map(([, name, value]) => [name, value.replace(/\s+/g, ' ').trim()]));
}

function block(css, pattern, label) {
  const match = css.match(pattern);
  if (!match) throw new Error(`Bloco de tema ausente: ${label}`);
  return declarations(match[1]);
}

// Snapshot only semantic values. The docs keep their own Fumadocs components
// and do not load the product's global CSS or its Kumo component bundle.
export async function syncTheme(source) {
  const designPath = 'src/web/styles/design.css';
  const kumoPath = 'node_modules/@cloudflare/kumo/dist/styles/theme-kumo.css';
  const standalonePath = 'node_modules/@cloudflare/kumo/dist/styles/kumo-standalone.css';
  const [design, kumo, standalone, packageJson] = await Promise.all([
    readFile(path.join(source, designPath), 'utf8'),
    readFile(path.join(source, kumoPath), 'utf8'),
    readFile(path.join(source, standalonePath), 'utf8'),
    readFile(path.join(source, 'node_modules/@cloudflare/kumo/package.json'), 'utf8'),
  ]);
  const palette = declarations(standalone.slice(0, standalone.indexOf('@layer base')));
  const fallback = kumo.slice(kumo.indexOf('@layer base'));
  const base = block(fallback, /\[data-theme="kumo"\]\s*\{([^}]+)\}/, 'Kumo light');
  const dark = block(fallback, /\[data-theme="kumo"\]\s*\[data-mode="dark"\]\s*\{([^}]+)\}/, 'Kumo dark');
  function resolve(value) {
    const variable = value.match(/^var\(\s*(--[\w-]+),\s*(.*)\)$/);
    return variable ? resolve((palette[variable[1]] ?? variable[2]).trim()) : value;
  }
  const modes = {};
  for (const mode of ['light', 'dark']) {
    const overrides = block(design, new RegExp(`:root\\[data-mode="${mode}"\\]\\s*\\{([^}]+)\\}`), `Caderninho ${mode}`);
    const values = { ...base, ...(mode === 'dark' ? dark : {}), ...overrides };
    modes[mode] = Object.fromEntries(tokens.map(token => {
      const value = values[`--${token}`];
      if (!value) throw new Error(`Token de tema ausente: ${token} (${mode})`);
      return [`--${token}`, resolve(value)];
    }));
  }
  const css = ['/* Generated by scripts/sync-theme.mjs from Caderninho and Kumo. */',
    ...Object.entries(modes).map(([mode, values]) => `${mode === 'light' ? ':root' : ':root.dark'} {\n${Object.entries(values).map(([key, value]) => `  ${key}: ${value};`).join('\n')}\n}`),
  ].join('\n\n') + '\n';
  await writeFile(path.join(root, 'app/caderninho-theme.css'), css);
  await writeFile(path.join(root, 'data/theme-manifest.json'), JSON.stringify({
    source: designPath,
    sourceSha256: createHash('sha256').update(design).digest('hex'),
    kumoVersion: JSON.parse(packageJson).version,
    kumoThemeSha256: createHash('sha256').update(kumo).digest('hex'),
    modes,
  }, null, 2) + '\n');
  console.log(`Temas sincronizados: ${tokens.length} tokens, claro e escuro, Kumo ${JSON.parse(packageJson).version}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await syncTheme(path.resolve(process.argv[2] ?? '../caderninho'));
}
